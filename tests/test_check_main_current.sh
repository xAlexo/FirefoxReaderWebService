#!/usr/bin/env bash
set -euo pipefail

script="$(cd "$(dirname "$0")/.." && pwd)/scripts/check-main-current.sh"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
failures=0

pass() { printf 'ok - %s\n' "$1"; }
fail() {
  printf 'not ok - %s\n' "$1" >&2
  failures=$((failures + 1))
}

zero_sha=$(printf '%040d' 0)
remote_sha=$(printf '%040d' 1)
main_delete="refs/heads/main $zero_sha refs/heads/main $remote_sha"
if printf '%s\n' "$main_delete" | "$script" origin; then
  fail 'reject deletion of main'
else
  pass 'reject deletion of main'
fi

repo="$tmp/repo"
mkdir -p "$repo"
git -C "$repo" init -q
git -C "$repo" checkout -q -b main
git -C "$repo" config user.name test
git -C "$repo" config user.email test@example.invalid
printf 'base\n' > "$repo/file"
git -C "$repo" add file
git -C "$repo" commit -q -m base
git init --bare -q "$tmp/origin.git"
git -C "$repo" remote add origin "$tmp/origin.git"
git -C "$repo" -c core.hooksPath=/dev/null push -q origin main
main_sha=$(git -C "$repo" rev-parse HEAD)
hook_path=$(cd "$repo" && git rev-parse --git-path hooks/pre-push)
[[ $hook_path == /* ]] || hook_path="$repo/$hook_path"
mkdir -p "$(dirname "$hook_path")"

cat > "$tmp/pre-commit-hook" <<'EOF'
#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 0123456789abcdef0123456789abcdef

# start templated
INSTALL_PYTHON=''
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-push)
# end templated

HERE="$(cd "$(dirname "$0")" && pwd)"
ARGS+=(--hook-dir "$HERE" -- "$@")

if [ -x "$INSTALL_PYTHON" ]; then
    exec "$INSTALL_PYTHON" -mpre_commit "${ARGS[@]}"
elif command -v pre-commit > /dev/null; then
    exec pre-commit "${ARGS[@]}"
else
    echo '`pre-commit` not found.  Did you forget to activate your virtualenv?' 1>&2
    exit 1
fi
EOF
cp "$tmp/pre-commit-hook" "$hook_path"
chmod +x "$hook_path"

bin="$tmp/bin"
mkdir -p "$bin"
cat > "$bin/pre-commit" <<'EOF'
#!/usr/bin/env bash
{
  printf '%s\n' "$*"
  cat
} > "$PRE_COMMIT_LOG"
exit "${PRE_COMMIT_EXIT:-0}"
EOF
chmod +x "$bin/pre-commit"

(cd "$repo" && "$script" --install)
if cmp -s "$tmp/pre-commit-hook" "$hook_path.pre-commit"; then
  pass 'preserve the existing pre-commit hook'
else
  fail 'preserve the existing pre-commit hook'
fi

log="$tmp/pre-commit.log"
payload="refs/heads/topic $remote_sha refs/heads/topic $zero_sha"
if printf '%s\n' "$payload" | \
  (cd "$repo" && PRE_COMMIT_LOG="$log" PATH="$bin:$PATH" \
    "$hook_path" upstream example-url); then
  pass 'run the preserved hook for other remotes'
else
  fail 'run the preserved hook for other remotes'
fi
if [[ -f $log ]] && grep -Fq upstream "$log" && grep -Fq "$payload" "$log"; then
  pass 'forward the original pre-push input'
else
  fail 'forward the original pre-push input'
fi

rm -f "$log"
chmod -x "$hook_path.pre-commit"
if printf '%s\n' "$payload" | \
  (cd "$repo" && PRE_COMMIT_LOG="$log" PATH="$bin:$PATH" \
    "$hook_path" upstream example-url); then
  fail 'refuse a non-executable saved hook'
else
  pass 'refuse a non-executable saved hook'
fi
if [[ ! -e $log ]]; then
  pass 'do not silently skip a non-executable saved hook'
else
  fail 'do not silently skip a non-executable saved hook'
fi
chmod +x "$hook_path.pre-commit"

valid_main="refs/heads/main $main_sha refs/heads/main $zero_sha"
rm -f "$log"
if printf '%s\n' "$valid_main" | \
  (cd "$repo" && PRE_COMMIT_LOG="$log" PATH="$bin:$PATH" \
    "$hook_path" origin "$tmp/origin.git"); then
  pass 'run the saved hook after a valid origin push'
else
  fail 'run the saved hook after a valid origin push'
fi
if [[ -f $log ]] && grep -Fq "$valid_main" "$log"; then
  pass 'forward origin push input to the saved hook'
else
  fail 'forward origin push input to the saved hook'
fi

rm -f "$log"
if printf '%s\n' "$main_delete" | \
  (cd "$repo" && PRE_COMMIT_LOG="$log" PATH="$bin:$PATH" \
    "$hook_path" origin example-url); then
  fail 'block main deletion before running pre-commit'
else
  pass 'block main deletion before running pre-commit'
fi
if [[ ! -e $log ]]; then
  pass 'skip pre-commit after a rejected push'
else
  fail 'skip pre-commit after a rejected push'
fi

if printf '%s\n' "$valid_main" | \
  (cd "$repo" && PRE_COMMIT_LOG="$log" PRE_COMMIT_EXIT=7 PATH="$bin:$PATH" \
    "$hook_path" origin "$tmp/origin.git"); then
  fail 'propagate a failing saved hook status'
else
  status=$?
  if [[ $status -eq 7 ]]; then
    pass 'propagate a failing saved hook status'
  else
    fail 'propagate a failing saved hook status'
  fi
fi

sed 's/0123456789abcdef0123456789abcdef/abcdef0123456789abcdef0123456789/' \
  "$tmp/pre-commit-hook" > "$tmp/updated-hook"
chmod +x "$tmp/updated-hook"
cp "$tmp/updated-hook" "$hook_path"
if (cd "$repo" && "$script" --install); then
  fail 'refuse to replace a newer pre-commit hook'
else
  pass 'refuse to replace a newer pre-commit hook'
fi
if cmp -s "$tmp/updated-hook" "$hook_path"; then
  pass 'leave the newer pre-commit hook intact'
else
  fail 'leave the newer pre-commit hook intact'
fi

exit "$failures"
